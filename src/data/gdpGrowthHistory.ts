export interface GdpGrowthPoint {
  year: number;
  country: number | null;
  world: number | null;
  japan: number | null;
  isForecast: boolean;
}

export function getGdpGrowthSeries(iso3: string): {
  hasData: boolean;
  points: GdpGrowthPoint[];
  latestValue: number | null;
  latestYear: number | null;
  avgRate: number | null;
} {
  const series = GDP_GROWTH_BY_ISO3[iso3.toUpperCase()];
  if (!series) {
    return { hasData: false, points: [], latestValue: null, latestYear: null, avgRate: null };
  }
  const japanSeries = GDP_GROWTH_BY_ISO3["JPN"] ?? [];
  const points: GdpGrowthPoint[] = GDP_GROWTH_YEARS.map((year, idx) => ({
    year,
    country: series[idx] ?? null,
    world: WORLD_GDP_GROWTH[idx] ?? null,
    japan: japanSeries[idx] ?? null,
    isForecast: year >= GDP_GROWTH_FORECAST_YEAR,
  }));

  let latestValue: number | null = null;
  let latestYear: number | null = null;
  const validValues: number[] = [];
  for (const p of points) {
    if (p.country !== null) {
      latestValue = p.country;
      latestYear = p.year;
      validValues.push(p.country);
    }
  }
  const avgRate =
    validValues.length > 0
      ? Number((validValues.reduce((a, b) => a + b, 0) / validValues.length).toFixed(1))
      : null;

  return {
    hasData: validValues.length >= 2,
    points,
    latestValue,
    latestYear,
    avgRate,
  };
}
