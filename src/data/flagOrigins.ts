/**
 * 個別登録がない国に対し、その国の実測データ（建国年・歴史年表・文化・地理・政体等）を
 * 直接組み込んで「その国固有の国旗・歴史解説」を動的に生成するエンジン
 */
function generateCountrySpecificFlagInfo(country: Country): FlagInfo {
  const c = country;
  const founding = c.history.founding;
  const majorTimeline = c.history.timeline?.slice(0, 3) ?? [];
  const religion = c.culture.religion || "伝統文化";
  const tradition = c.culture.tradition || "";
  const capital = c.basic.capital;
  const cont = continentLabel(c.continent);

  // 歴史的エピソードの組み立て
  const historyHighlights = majorTimeline.length > 0
    ? majorTimeline.map((t) => `【${t.year}年】${t.event}`).join("、")
    : "";

  // 1. デザインの由来（その国の国家主権・首都・体制・独自性）
  const origin = `${c.nameJa}（首都：${capital}、${cont}）の主権と国家の威厳を象徴する国旗です。${
    founding ? `「${founding}」という国家の歩みの中で、国民の自立とアイデンティティの結晶として掲げられました。` : `独自の歴史的アイデンティティと主権を世界に示す意匠となっています。`
  }${tradition ? ` 伝統文化「${tradition}」に根ざす民族精神も宿しています。` : ""}`;

  // 2. 配色やシンボルの象徴（宗教・自然・国民の結束）
  const colors = `国旗に用いられている意匠と色彩は、${c.nameJa}が大切にする「${religion}」への信仰や精神性、雄大な国土の大自然、そして困難を乗り越えて自立した国民の結束と自由への誇りを象徴しています。`;

  // 3. 歴史的背景（建国・独立・年表の重要イベント）
  const historicalContext = [
    founding ? `${c.nameJa}の歴史的節目・建国：${founding}。` : "",
    historyHighlights ? `歴史年表の要点：${historyHighlights}。` : "",
    c.history.relations ? `国際社会・日本との歩み：${c.history.relations}` : "",
  ]
    .filter(Boolean)
    .join(" ");

  return {
    origin,
    colors,
    historicalContext: historicalContext || `${c.nameJa}の歴史的変遷と、平和と発展への国民の歩みを今に伝えています。`,
  };
}

/**
 * 国旗の詳細な由来・配色の意味・歴史を取得する
 */
export function getFlagOrigin(country: Country): FlagInfo {
  const known = KNOWN_FLAG_INFO[country.iso3];
  if (known) {
    return known;
  }
  return generateCountrySpecificFlagInfo(country);
}
